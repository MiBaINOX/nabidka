function initCounters() {
  const counters = document.querySelectorAll('.counter[data-target]');
  if (!counters.length) return;

  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    return;
  }

  const observer = new IntersectionObserver(function (entries, obs) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        const el = entry.target;
        const target = parseInt(el.getAttribute('data-target') || el.textContent, 10);
        if (isNaN(target)) return;

        el.textContent = '0';
        const duration = 1600;
        const startTime = performance.now();

        function updateCount(currentTime) {
          const elapsed = currentTime - startTime;
          const progress = Math.min(elapsed / duration, 1);
          const easeOut = 1 - Math.pow(1 - progress, 3);
          const currentVal = Math.floor(easeOut * target);

          el.textContent = currentVal;

          if (progress < 1) {
            requestAnimationFrame(updateCount);
          } else {
            el.textContent = target;
          }
        }

        requestAnimationFrame(updateCount);
        obs.unobserve(el);
      }
    });
  }, { threshold: 0.2 });

  counters.forEach(function (counter) {
    observer.observe(counter);
  });
}

function initScrollReveal() {
  const reveals = document.querySelectorAll('.reveal');
  if (!reveals.length) return;

  const observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        entry.target.classList.add('active');
      }
    });
  }, { threshold: 0.1 });

  reveals.forEach(function (el) {
    observer.observe(el);
  });
}

function initCatalogFilters() {
  const filterBtns = document.querySelectorAll('.filter-btn');
  const searchInput = document.getElementById('catalogSearch');
  const cards = document.querySelectorAll('.cat-card');
  const counterEl = document.getElementById('searchCounter');

  let activeCategory = 'all';
  let searchQuery = '';

  function applyFilter() {
    let visibleCount = 0;

    cards.forEach(function (card) {
      const cardCat = card.getAttribute('data-category') || '';
      const cardTitle = (card.querySelector('.item-title')?.textContent || '').toLowerCase();
      const cardDesc = (card.querySelector('.item-desc')?.textContent || '').toLowerCase();
      const cardDisp = (card.getAttribute('data-disp') || '').toLowerCase();

      const matchesCat = activeCategory === 'all' || cardCat === activeCategory;
      const matchesSearch = !searchQuery || cardTitle.includes(searchQuery) || cardDesc.includes(searchQuery) || cardDisp.includes(searchQuery);

      if (matchesCat && matchesSearch) {
        card.style.display = '';
        visibleCount++;
      } else {
        card.style.display = 'none';
      }
    });

    if (counterEl) {
      if (visibleCount === cards.length) {
        counterEl.textContent = cards.length + ' modelů v nabídce';
      } else {
        counterEl.textContent = visibleCount + ' modelů odpovídá výběru';
      }
    }
  }

  filterBtns.forEach(function (btn) {
    btn.addEventListener('click', function () {
      filterBtns.forEach(function (b) { b.classList.remove('active'); });
      btn.classList.add('active');
      activeCategory = btn.getAttribute('data-category') || 'all';
      applyFilter();
    });
  });

  if (searchInput) {
    searchInput.addEventListener('input', function (e) {
      searchQuery = (e.target.value || '').trim().toLowerCase();
      applyFilter();
    });
  }
}

function initModal() {
  const backdrop = document.getElementById('techModalBackdrop');
  const closeBtn = document.getElementById('techModalClose');
  const modalFooterClose = document.getElementById('modalFooterClose');
  const detailBtns = document.querySelectorAll('.btn-detail[data-open-id]');

  if (!backdrop) return;

  function closeModal() {
    backdrop.style.display = 'none';
    document.body.style.overflow = '';
  }

  function openModal(id) {
    const data = TECH_DATA[id];
    if (!data) return;

    document.getElementById('modalTitle').textContent = data.title;
    document.getElementById('modalDisposition').textContent = data.disposition + ' | ' + data.floor_area;
    document.getElementById('modalShortDesc').textContent = data.desc;

    const mainImg = document.getElementById('modalMainImg');
    const planImg = document.getElementById('modalPlanImg');
    if (mainImg) mainImg.src = data.image;
    if (planImg) planImg.src = data.plan_image;

    const specsTbody = document.getElementById('modalSpecsTbody');
    if (specsTbody) {
      specsTbody.innerHTML = '';
      data.specs.forEach(function (pair) {
        const tr = document.createElement('tr');
        const tdKey = document.createElement('td');
        tdKey.style.fontWeight = '600';
        tdKey.style.width = '40%';
        tdKey.textContent = pair[0];
        const tdVal = document.createElement('td');
        tdVal.textContent = pair[1];
        tr.appendChild(tdKey);
        tr.appendChild(tdVal);
        specsTbody.appendChild(tr);
      });
    }

    const roomsTbody = document.getElementById('modalRoomsTbody');
    if (roomsTbody) {
      roomsTbody.innerHTML = '';
      data.rooms.forEach(function (r) {
        const tr = document.createElement('tr');
        const tdOzn = document.createElement('td');
        tdOzn.textContent = r[0];
        tdOzn.style.fontWeight = '700';
        tdOzn.style.width = '15%';
        const tdNazev = document.createElement('td');
        tdNazev.textContent = r[1];
        const tdPlocha = document.createElement('td');
        tdPlocha.textContent = r[2];
        tdPlocha.style.fontWeight = '600';
        tdPlocha.style.textAlign = 'right';
        tdPlocha.style.width = '25%';
        tr.appendChild(tdOzn);
        tr.appendChild(tdNazev);
        tr.appendChild(tdPlocha);
        roomsTbody.appendChild(tr);
      });
    }

    const featuresList = document.getElementById('modalFeaturesList');
    if (featuresList) {
      featuresList.innerHTML = '';
      data.features.forEach(function (feat) {
        const li = document.createElement('li');
        li.textContent = feat;
        featuresList.appendChild(li);
      });
    }

    const modalInquiryBtn = document.getElementById('modalInquiryBtn');
    if (modalInquiryBtn) {
      modalInquiryBtn.setAttribute('href', '#kontakt');
      modalInquiryBtn.onclick = function () {
        closeModal();
        const select = document.getElementById('contactSubject');
        if (select) {
          for (let i = 0; i < select.options.length; i++) {
            if (select.options[i].text.toLowerCase().includes(data.title.toLowerCase().split(' ')[1] || '')) {
              select.selectedIndex = i;
              break;
            }
          }
        }
      };
    }

    backdrop.style.display = 'flex';
    document.body.style.overflow = 'hidden';
  }

  detailBtns.forEach(function (btn) {
    btn.addEventListener('click', function () {
      const id = btn.getAttribute('data-open-id');
      openModal(id);
    });
  });

  if (closeBtn) closeBtn.addEventListener('click', closeModal);
  if (modalFooterClose) modalFooterClose.addEventListener('click', closeModal);

  backdrop.addEventListener('click', function (e) {
    if (e.target === backdrop) {
      closeModal();
    }
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && backdrop.style.display === 'flex') {
      closeModal();
    }
  });
}


document.addEventListener("DOMContentLoaded", function () {
  const toggleBtn = document.getElementById("mobileToggle");
  const nav = document.querySelector(".header-nav");
  if (toggleBtn && nav) {
    toggleBtn.addEventListener("click", function () {
      nav.classList.toggle("is-open");
    });
    nav.querySelectorAll("a").forEach(function (link) {
      link.addEventListener("click", function () {
        nav.classList.remove("is-open");
      });
    });
  }

  const counters = document.querySelectorAll(".counter");
  if (counters.length > 0) {
    if (!window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      const counterObserver = new IntersectionObserver(function (entries, observer) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            const el = entry.target;
            const target = parseInt(el.getAttribute("data-target") || el.textContent, 10);
            if (!isNaN(target)) {
              el.textContent = "0";
              const duration = 1400;
              const start = performance.now();
              function step(now) {
                const progress = Math.min((now - start) / duration, 1);
                const easeOut = 1 - Math.pow(1 - progress, 3);
                const current = Math.floor(easeOut * target);
                el.textContent = current;
                if (progress < 1) {
                  requestAnimationFrame(step);
                } else {
                  el.textContent = target;
                }
              }
              requestAnimationFrame(step);
            }
            observer.unobserve(el);
          }
        });
      }, { threshold: 0.2 });

      counters.forEach(function (c) {
        counterObserver.observe(c);
      });
    }
  }

  const filterBtns = document.querySelectorAll(".filter-btn");
  const searchInput = document.getElementById("catalogSearch");
  const cards = document.querySelectorAll(".bento-card");
  const counterEl = document.getElementById("searchCounter");

  function filterCatalog() {
    const activeCategory = document.querySelector(".filter-btn.active") ? document.querySelector(".filter-btn.active").getAttribute("data-filter") : "all";
    const query = searchInput ? searchInput.value.toLowerCase().trim() : "";
    let visibleCount = 0;

    cards.forEach(function (card) {
      const cat = card.getAttribute("data-category") || "";
      const text = card.textContent.toLowerCase();

      const matchCat = (activeCategory === "all" || cat === activeCategory);
      const matchQuery = (!query || text.indexOf(query) !== -1);

      if (matchCat && matchQuery) {
        card.style.display = "flex";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (counterEl) {
      counterEl.textContent = visibleCount + " technologií";
    }
  }

  filterBtns.forEach(function (btn) {
    btn.addEventListener("click", function () {
      filterBtns.forEach(function (b) { b.classList.remove("active"); });
      this.classList.add("active");
      filterCatalog();
    });
  });

  if (searchInput) {
    searchInput.addEventListener("input", filterCatalog);
  }

  const modal = document.getElementById("techModalBackdrop");
  const closeBtn = document.getElementById("techModalClose");
  const modalTitle = document.getElementById("modalTitle");
  const modalBadge = document.getElementById("modalBadge");
  const modalNorm = document.getElementById("modalNorm");
  const modalImg = document.getElementById("modalImg");
  const modalDesc = document.getElementById("modalDesc");
  const modalTableBody = document.getElementById("modalTableBody");

  window.openTechModal = function (techId) {
    const data = techCatalogData[techId];
    if (!data || !modal) return;

    if (modalTitle) modalTitle.textContent = data.title;
    if (modalBadge) modalBadge.textContent = data.badge;
    if (modalNorm) modalNorm.textContent = data.norm;
    if (modalImg) {
      modalImg.src = data.image;
      modalImg.alt = data.title;
    }
    if (modalDesc) modalDesc.textContent = data.desc;

    if (modalTableBody && data.table) {
      modalTableBody.innerHTML = "";
      data.table.forEach(function (row) {
        const tr = document.createElement("tr");
        row.forEach(function (col) {
          const td = document.createElement("td");
          td.textContent = col;
          tr.appendChild(td);
        });
        modalTableBody.appendChild(tr);
      });
    }

    modal.classList.add("active");
    modal.style.display = "flex";
    document.body.style.overflow = "hidden";
  };

  window.closeTechModal = function () {
    if (!modal) return;
    modal.classList.remove("active");
    modal.style.display = "none";
    document.body.style.overflow = "";
  };

  if (closeBtn) {
    closeBtn.addEventListener("click", window.closeTechModal);
  }

  if (modal) {
    modal.addEventListener("click", function (e) {
      if (e.target === modal) {
        window.closeTechModal();
      }
    });
  }

  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape") {
      window.closeTechModal();
    }
  });

  cards.forEach(function (card) {
    card.addEventListener("click", function (e) {
      const techId = this.getAttribute("data-id") || this.getAttribute("data-open-tech");
      if (techId) {
        window.openTechModal(techId);
      }
    });
  });

  const wallSelect = document.getElementById("calcWall");
  const insSelect = document.getElementById("calcIns");
  const targetSelect = document.getElementById("calcTarget");
  const resThick = document.getElementById("resThick");
  const resU = document.getElementById("resU");
  const resR = document.getElementById("resR");
  const resSavings = document.getElementById("resSavings");

  function recalculateInsulation() {
    if (!wallSelect || !insSelect || !targetSelect) return;

    const wallR = parseFloat(wallSelect.value);
    const lambda = parseFloat(insSelect.value);
    const targetU = parseFloat(targetSelect.value);

    const targetR = 1 / targetU;
    const neededR = Math.max(0, targetR - wallR - 0.17);
    const neededThickMeters = neededR * lambda;
    let cm = Math.ceil((neededThickMeters * 100) / 2) * 2;
    if (cm < 8) cm = 8;
    if (cm > 30) cm = 30;

    const finalR = wallR + 0.17 + (cm / 100) / lambda;
    const finalU = 1 / finalR;
    const initialU = 1 / (wallR + 0.17);
    const savingsPercent = Math.round(((initialU - finalU) / initialU) * 100);

    if (resThick) resThick.textContent = cm + " cm";
    if (resU) resU.textContent = finalU.toFixed(2) + " W/m²K";
    if (resR) resR.textContent = finalR.toFixed(2) + " m²K/W";
    if (resSavings) resSavings.textContent = savingsPercent + " %";
  }

  if (wallSelect && insSelect && targetSelect) {
    wallSelect.addEventListener("change", recalculateInsulation);
    insSelect.addEventListener("change", recalculateInsulation);
    targetSelect.addEventListener("change", recalculateInsulation);
    recalculateInsulation();
  }

  const contactForm = document.getElementById("inquiryForm");
  if (contactForm) {
    contactForm.addEventListener("submit", function (e) {
      e.preventDefault();
      const statusBox = document.getElementById("formStatus");
      if (statusBox) {
        statusBox.textContent = "Děkujeme za poptávku. Specialista SANCO FASÁDY vás bude kontaktovat.";
        statusBox.style.display = "block";
        contactForm.reset();
      }
    });
  }

  const urlParams = new URLSearchParams(window.location.search);
  if (urlParams.get("ref") === "nabidka") {
    const banner = document.createElement("div");
    banner.className = "ref-nabidka-banner";
    banner.style.cssText = "background: #0284c7; color: #ffffff; text-align: center; padding: 8px 16px; font-size: 0.88rem; font-weight: 600;";
    banner.textContent = "Interaktivní návrh modernizace webové prezentace pro společnost SANCO FASÁDY s.r.o.";
    document.body.insertBefore(banner, document.body.firstChild);
  }
});

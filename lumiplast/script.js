let currentLang = "cs";

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("lumiplast_lang", lang);

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  const dict = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });
}

function initLangSwitcher() {
  const saved = localStorage.getItem("lumiplast_lang");
  if (saved && translations[saved]) {
    setLanguage(saved);
  }

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      const l = btn.getAttribute("data-lang");
      setLanguage(l);
    });
  });
}

function initCatalog() {
  const searchInput = document.getElementById("searchInput");
  const filterButtons = document.querySelectorAll(".filter-btn");
  const cards = document.querySelectorAll(".cat-card");
  const counterSpan = document.getElementById("itemCount");
  let activeCategory = "all";

  function filterCards() {
    const q = (searchInput ? searchInput.value : "").toLowerCase().trim();
    let visibleCount = 0;

    cards.forEach(card => {
      const cat = card.getAttribute("data-cat") || "";
      const text = card.textContent.toLowerCase();
      const matchesCat = (activeCategory === "all" || cat.toLowerCase().includes(activeCategory.toLowerCase()));
      const matchesQuery = !q || text.includes(q);

      if (matchesCat && matchesQuery) {
        card.style.display = "flex";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (counterSpan) {
      counterSpan.textContent = visibleCount;
    }
  }

  if (searchInput) {
    searchInput.addEventListener("input", filterCards);
  }

  filterButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      filterButtons.forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      activeCategory = btn.getAttribute("data-cat") || "all";
      filterCards();
    });
  });

  filterCards();
}

function initModal() {
  const backdrop = document.getElementById("techModalBackdrop");
  const closeBtn = document.getElementById("techModalClose");
  const modalTitle = document.getElementById("modalTitle");
  const modalBadge = document.getElementById("modalBadge");
  const modalImg = document.getElementById("modalImg");
  const modalDesc = document.getElementById("modalDesc");
  const modalSpecsBody = document.getElementById("modalSpecsBody");
  const modalInquire = document.getElementById("modalInquireBtn");

  function openTechModal(techId) {
    const data = techData[techId];
    if (!data || !backdrop) return;

    if (modalTitle) modalTitle.textContent = data.name;
    if (modalBadge) modalBadge.textContent = data.category;
    if (modalImg) {
      modalImg.src = data.image;
      modalImg.alt = data.name;
    }
    if (modalDesc) modalDesc.textContent = data.desc;

    if (modalSpecsBody) {
      modalSpecsBody.innerHTML = "";
      data.specs.forEach(s => {
        const row = document.createElement("tr");
        const th = document.createElement("th");
        th.textContent = s.key;
        const td = document.createElement("td");
        td.textContent = s.val;
        row.appendChild(th);
        row.appendChild(td);
        modalSpecsBody.appendChild(row);
      });
    }

    backdrop.classList.add("active");
    backdrop.style.display = "flex";
    backdrop.style.visibility = "visible";
    backdrop.style.opacity = "1";
    document.body.style.overflow = "hidden";
  }

  function closeTechModal() {
    if (!backdrop) return;
    backdrop.classList.remove("active");
    backdrop.style.display = "none";
    backdrop.style.visibility = "hidden";
    backdrop.style.opacity = "0";
    document.body.style.overflow = "";
  }

  document.querySelectorAll("[data-open-tech]").forEach(el => {
    el.addEventListener("click", e => {
      e.preventDefault();
      const techId = el.getAttribute("data-open-tech");
      openTechModal(techId);
    });
  });

  if (closeBtn) {
    closeBtn.addEventListener("click", closeTechModal);
  }

  if (backdrop) {
    backdrop.addEventListener("click", e => {
      if (e.target === backdrop) {
        closeTechModal();
      }
    });
  }

  document.addEventListener("keydown", e => {
    if (e.key === "Escape" && backdrop && backdrop.classList.contains("active")) {
      closeTechModal();
    }
  });

  if (modalInquire) {
    modalInquire.addEventListener("click", () => {
      closeTechModal();
      const target = document.getElementById("kontakt");
      if (target) {
        target.scrollIntoView({ behavior: "smooth" });
      }
    });
  }
}

function initNavToggle() {
  const toggle = document.querySelector(".nav-toggle");
  const nav = document.querySelector(".main-nav");
  if (toggle && nav) {
    toggle.addEventListener("click", () => {
      nav.classList.toggle("active");
    });

    document.querySelectorAll(".nav-link").forEach(link => {
      link.addEventListener("click", () => {
        nav.classList.remove("active");
      });
    });
  }
}

function initScrollReveal() {
  const targets = document.querySelectorAll(".feature-card, .cat-card, .stat-box, .about-grid, .contact-grid");
  if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver((entries, obs) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.style.opacity = "1";
          entry.target.style.transform = "translateY(0)";
          obs.unobserve(entry.target);
        }
      });
    }, { threshold: 0.1 });

    targets.forEach(t => {
      t.style.opacity = "0";
      t.style.transform = "translateY(16px)";
      t.style.transition = "opacity 0.5s ease-out, transform 0.5s ease-out";
      observer.observe(t);
    });
  }
}

function initContactForm() {
  const form = document.getElementById("contactForm");
  if (form) {
    form.addEventListener("submit", e => {
      e.preventDefault();
      const btn = form.querySelector("button[type='submit']");
      const originalText = btn ? btn.textContent : "";
      if (btn) {
        btn.textContent = currentLang === "en" ? "Inquiry Sent! Thank you." : currentLang === "de" ? "Anfrage gesendet! Vielen Dank." : "Poptávka odeslána! Děkujeme.";
        btn.style.backgroundColor = "#16a34a";
      }
      setTimeout(() => {
        form.reset();
        if (btn) {
          btn.textContent = originalText;
          btn.style.backgroundColor = "";
        }
      }, 3500);
    });
  }
}


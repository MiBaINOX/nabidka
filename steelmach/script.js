function initCounters() {
  const counters = document.querySelectorAll(".counter[data-target]");
  if (!counters.length) return;

  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      obs.unobserve(el);

      const target = parseInt(el.getAttribute("data-target") || el.textContent, 10);
      if (isNaN(target)) return;

      if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
        el.textContent = target;
        return;
      }

      el.textContent = "0";
      const duration = 1500;
      let start = null;

      function step(timestamp) {
        if (!start) start = timestamp;
        const progress = Math.min((timestamp - start) / duration, 1);
        const easeOut = 1 - Math.pow(1 - progress, 3);
        const current = Math.floor(easeOut * target);
        el.textContent = current;

        if (progress < 1) {
          window.requestAnimationFrame(step);
        } else {
          el.textContent = target;
        }
      }

      window.requestAnimationFrame(step);
    });
  }, { threshold: 0.3 });

  counters.forEach(c => observer.observe(c));
}

function initCatalog() {
  const searchInput = document.getElementById("catalogSearch");
  const filterBtns = document.querySelectorAll(".filter-tab-btn");
  const cards = document.querySelectorAll(".catalog-card");
  const counterEl = document.getElementById("searchCounter");

  let currentCategory = "all";
  let searchQuery = "";

  function updateFilter() {
    let visibleCount = 0;

    cards.forEach(card => {
      const cardCategory = card.getAttribute("data-category") || "";
      const cardText = card.textContent.toLowerCase();

      const matchesCat = currentCategory === "all" || cardCategory === currentCategory;
      const matchesSearch = !searchQuery || cardText.includes(searchQuery);

      if (matchesCat && matchesSearch) {
        card.style.display = "flex";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (counterEl) {
      counterEl.textContent = visibleCount + " položek výrobních kapacit";
    }
  }

  if (searchInput) {
    searchInput.addEventListener("input", function (e) {
      searchQuery = e.target.value.trim().toLowerCase();
      updateFilter();
    });
  }

  filterBtns.forEach(btn => {
    btn.addEventListener("click", function () {
      filterBtns.forEach(b => b.classList.remove("active"));
      this.classList.add("active");
      currentCategory = this.getAttribute("data-filter") || "all";
      updateFilter();
    });
  });
}

function initModal() {
  const backdrop = document.getElementById("techModalBackdrop");
  const closeBtn = document.getElementById("techModalClose");
  const modalFooterClose = document.getElementById("modalFooterClose");
  const modalTitle = document.getElementById("modalTitle");
  const modalBadge = document.getElementById("modalBadge");
  const modalImage = document.getElementById("modalImage");
  const modalDesc = document.getElementById("modalDesc");
  const modalTableBody = document.getElementById("modalTableBody");

  if (!backdrop) return;

  function openModal(id) {
    const item = techData[id];
    if (!item) return;

    if (modalTitle) modalTitle.textContent = item.title;
    if (modalBadge) modalBadge.textContent = item.badge;
    if (modalImage) {
      modalImage.src = item.image;
      modalImage.alt = item.title;
    }
    if (modalDesc) modalDesc.textContent = item.description;

    if (modalTableBody) {
      modalTableBody.innerHTML = "";
      item.specs.forEach(([label, value]) => {
        const tr = document.createElement("tr");
        const th = document.createElement("th");
        th.textContent = label;
        const td = document.createElement("td");
        td.textContent = value;
        tr.appendChild(th);
        tr.appendChild(td);
        modalTableBody.appendChild(tr);
      });
    }

    backdrop.classList.add("active");
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    backdrop.classList.remove("active");
    document.body.style.overflow = "";
  }

  document.querySelectorAll(".card-btn[data-tech-id]").forEach(btn => {
    btn.addEventListener("click", function (e) {
      e.preventDefault();
      const techId = this.getAttribute("data-tech-id");
      openModal(techId);
    });
  });

  if (closeBtn) closeBtn.addEventListener("click", closeModal);
  if (modalFooterClose) modalFooterClose.addEventListener("click", closeModal);

  backdrop.addEventListener("click", function (e) {
    if (e.target === backdrop) closeModal();
  });

  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && backdrop.classList.contains("active")) {
      closeModal();
    }
  });
}

function initNavigation() {
  const toggle = document.querySelector(".mobile-nav-toggle");
  const nav = document.querySelector(".main-nav");

  if (toggle && nav) {
    toggle.addEventListener("click", function () {
      nav.classList.toggle("open");
    });

    nav.querySelectorAll(".nav-link").forEach(link => {
      link.addEventListener("click", function () {
        nav.classList.remove("open");
      });
    });
  }
}

function initInquiryForm() {
  const form = document.getElementById("inquiryForm");
  const status = document.getElementById("formStatus");

  if (!form || !status) return;

  form.addEventListener("submit", function (e) {
    e.preventDefault();
    status.className = "form-status success";
    status.textContent = "Děkujeme za poptávku. Technické oddělení STEELMach s.r.o. vás bude kontaktovat s návrhem výrobního postupu.";
    form.reset();
  });
}

function checkOfferReferral() {
  const params = new URLSearchParams(window.location.search);
  const bar = document.getElementById("nabidkaBar");
  if (bar && (params.get("ref") === "nabidka" || params.get("utm_source") === "nabidka")) {
    bar.classList.add("active");
  }
}

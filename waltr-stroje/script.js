function initRefBanner() {
  const urlParams = new URLSearchParams(window.location.search);
  const banner = document.getElementById("refBanner");
  const closeBtn = document.getElementById("closeBannerBtn");
  if (!banner) return;

  if (urlParams.get("ref") === "nabidka" && !sessionStorage.getItem("hide_ref_banner")) {
    banner.style.display = "block";
  }

  if (closeBtn) {
    closeBtn.addEventListener("click", function () {
      banner.style.display = "none";
      sessionStorage.setItem("hide_ref_banner", "true");
    });
  }
}

function initCounters() {
  const counters = document.querySelectorAll(".counter");
  if (!counters.length) return;

  const observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const target = parseInt(el.getAttribute("data-target") || el.textContent, 10);

      if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
        observer.unobserve(el);
        return;
      }

      el.textContent = "0";
      const duration = 1400;
      const startTime = performance.now();

      function updateCounter(currentTime) {
        const elapsed = currentTime - startTime;
        const progress = Math.min(elapsed / duration, 1);
        const easeOut = 1 - Math.pow(1 - progress, 3);
        const currentVal = Math.round(target * easeOut);
        el.textContent = currentVal;

        if (progress < 1) {
          requestAnimationFrame(updateCounter);
        } else {
          el.textContent = target;
          observer.unobserve(el);
        }
      }

      requestAnimationFrame(updateCounter);
    });
  }, { threshold: 0.2 });

  counters.forEach(function (c) {
    observer.observe(c);
  });
}

function initCatalogFilters() {
  const filterTabs = document.querySelectorAll(".filter-tab");
  const searchInput = document.getElementById("catalogSearch");
  const clearBtn = document.getElementById("clearSearchBtn");
  const cards = document.querySelectorAll(".cat-card");
  const counterEl = document.getElementById("searchCounter");

  let activeCategory = "all";
  let activeQuery = "";

  function applyFilter() {
    let visibleCount = 0;
    const query = activeQuery.toLowerCase().trim();

    cards.forEach(function (card) {
      const cardCat = card.getAttribute("data-category");
      const cardText = card.textContent.toLowerCase();

      const matchesCat = (activeCategory === "all" || cardCat === activeCategory);
      const matchesText = (!query || cardText.indexOf(query) !== -1);

      if (matchesCat && matchesText) {
        card.style.display = "flex";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (counterEl) {
      counterEl.textContent = visibleCount;
    }

    if (clearBtn) {
      clearBtn.style.display = query ? "inline-flex" : "none";
    }
  }

  filterTabs.forEach(function (tab) {
    tab.addEventListener("click", function () {
      filterTabs.forEach(function (t) { t.classList.remove("active"); });
      tab.classList.add("active");
      activeCategory = tab.getAttribute("data-filter");
      applyFilter();
    });
  });

  if (searchInput) {
    searchInput.addEventListener("input", function (e) {
      activeQuery = e.target.value;
      applyFilter();
    });
  }

  if (clearBtn && searchInput) {
    clearBtn.addEventListener("click", function () {
      searchInput.value = "";
      activeQuery = "";
      applyFilter();
      searchInput.focus();
    });
  }
}

function initTechModal() {
  const modal = document.getElementById("techModalBackdrop");
  const closeBtn = document.getElementById("techModalClose");
  const dismissBtn = document.getElementById("modalDismissBtn");
  const inquireBtn = document.getElementById("modalInquireBtn");

  const modalTitle = document.getElementById("modalTitle");
  const modalBadge = document.getElementById("modalBadge");
  const modalImage = document.getElementById("modalImage");
  const modalDesc = document.getElementById("modalDesc");
  const modalSpecsBody = document.getElementById("modalSpecsBody");

  if (!modal) return;

  function openModal(id) {
    const data = TECH_DATA[id];
    if (!data) return;

    modalTitle.textContent = data.title;
    modalBadge.textContent = data.badge;
    modalImage.src = data.image;
    modalImage.alt = data.title;
    modalDesc.textContent = data.desc;

    let specsHtml = "";
    data.specs.forEach(function (spec) {
      specsHtml += "<tr><th>" + spec[0] + "</th><td>" + spec[1] + "</td></tr>";
    });
    modalSpecsBody.innerHTML = specsHtml;

    modal.classList.add("active");
    modal.style.display = "flex";
    modal.style.visibility = "visible";
    modal.style.opacity = "1";
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    modal.classList.remove("active");
    modal.style.display = "none";
    document.body.style.overflow = "";
  }

  document.querySelectorAll(".cat-card").forEach(function (card) {
    card.addEventListener("click", function (e) {
      const id = card.getAttribute("data-id");
      openModal(id);
    });
  });

  document.querySelectorAll(".btn-open-detail").forEach(function (btn) {
    btn.addEventListener("click", function (e) {
      e.stopPropagation();
      const id = btn.getAttribute("data-target-id");
      openModal(id);
    });
  });

  if (closeBtn) closeBtn.addEventListener("click", closeModal);
  if (dismissBtn) dismissBtn.addEventListener("click", closeModal);

  modal.addEventListener("click", function (e) {
    if (e.target === modal) {
      closeModal();
    }
  });

  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && modal.classList.contains("active")) {
      closeModal();
    }
  });

  if (inquireBtn) {
    inquireBtn.addEventListener("click", function () {
      closeModal();
    });
  }
}

function initNavToggle() {
  const toggle = document.getElementById("navToggle");
  const nav = document.getElementById("mainNav");
  if (!toggle || !nav) return;

  toggle.addEventListener("click", function () {
    nav.classList.toggle("open");
  });

  nav.querySelectorAll(".nav-link").forEach(function (link) {
    link.addEventListener("click", function () {
      nav.classList.remove("open");
    });
  });
}


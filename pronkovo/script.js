function initDemoBar() {
  const bar = document.getElementById('demoOfferBar');
  const closeBtn = document.getElementById('closeDemoBar');
  if (!bar) return;
  const params = new URLSearchParams(window.location.search);
  if (params.get('ref') === 'nabidka' || window.location.hash.includes('ref=nabidka')) {
    bar.classList.add('active');
  }
  if (closeBtn) {
    closeBtn.addEventListener('click', () => {
      bar.classList.remove('active');
    });
  }
}

function initMobileNav() {
  const toggle = document.getElementById('mobileNavToggle');
  const nav = document.getElementById('mainNav');
  if (!toggle || !nav) return;
  toggle.addEventListener('click', () => {
    nav.classList.toggle('mobile-active');
  });
  nav.querySelectorAll('.nav-link').forEach(link => {
    link.addEventListener('click', () => {
      nav.classList.remove('mobile-active');
    });
  });
}

function initTabs() {
  const buttons = document.querySelectorAll('.tab-btn');
  const panes = document.querySelectorAll('.tab-pane');
  buttons.forEach(btn => {
    btn.addEventListener('click', () => {
      buttons.forEach(b => b.classList.remove('active'));
      panes.forEach(p => p.classList.remove('active'));
      btn.classList.add('active');
      const targetId = btn.getAttribute('data-tab');
      const targetPane = document.getElementById(targetId);
      if (targetPane) {
        targetPane.classList.add('active');
      }
    });
  });
}

function initCatalog() {
  const searchInput = document.getElementById('catalogSearch');
  const filterBtns = document.querySelectorAll('.filter-btn');
  const cards = document.querySelectorAll('.catalog-item');
  const countEl = document.getElementById('itemCount');

  let activeCategory = 'all';
  let searchTerm = '';

  function applyFilters() {
    let visibleCount = 0;
    cards.forEach(card => {
      const cardCat = card.getAttribute('data-category');
      const cardText = card.innerText.toLowerCase();
      const matchesCat = (activeCategory === 'all' || cardCat === activeCategory);
      const matchesSearch = (!searchTerm || cardText.includes(searchTerm));
      if (matchesCat && matchesSearch) {
        card.style.display = 'flex';
        visibleCount++;
      } else {
        card.style.display = 'none';
      }
    });
    if (countEl) {
      countEl.textContent = String(visibleCount);
    }
  }

  filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      filterBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      activeCategory = btn.getAttribute('data-category');
      applyFilters();
    });
  });

  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      searchTerm = e.target.value.trim().toLowerCase();
      applyFilters();
    });
  }
}

function initModal() {
  const modal = document.getElementById('techModalBackdrop');
  const closeBtn = document.getElementById('techModalClose');
  const inquireBtn = document.getElementById('modalInquireBtn');
  const catEl = document.getElementById('modalCategory');
  const titleEl = document.getElementById('modalTitle');
  const imgEl = document.getElementById('modalImg');
  const descEl = document.getElementById('modalDesc');
  const specsBody = document.getElementById('modalSpecsBody');
  const advList = document.getElementById('modalAdvantages');

  if (!modal) return;

  function openItem(itemId) {
    const item = TECH_CATALOG.find(i => i.id === itemId);
    if (!item) return;

    if (catEl) catEl.textContent = item.category_name || 'Kovovýroba & Strojírenství';
    if (titleEl) titleEl.textContent = item.title;
    if (imgEl) {
      imgEl.src = item.image;
      imgEl.alt = item.title;
    }
    if (descEl) descEl.textContent = item.description;

    if (specsBody) {
      specsBody.innerHTML = '';
      if (item.specs) {
        Object.entries(item.specs).forEach(([k, v]) => {
          const tr = document.createElement('tr');
          const th = document.createElement('th');
          th.textContent = k;
          const td = document.createElement('td');
          td.textContent = v;
          tr.appendChild(th);
          tr.appendChild(td);
          specsBody.appendChild(tr);
        });
      }
    }

    if (advList) {
      advList.innerHTML = '';
      if (item.advantages) {
        item.advantages.forEach(adv => {
          const li = document.createElement('li');
          li.textContent = adv;
          advList.appendChild(li);
        });
      }
    }

    modal.classList.add('active');
    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
  }

  function closeModal() {
    modal.classList.remove('active');
    modal.style.display = 'none';
    document.body.style.overflow = '';
  }

  document.querySelectorAll('[data-open-tech]').forEach(card => {
    card.addEventListener('click', (e) => {
      const itemId = card.getAttribute('data-open-tech');
      openItem(itemId);
    });
  });

  if (closeBtn) {
    closeBtn.addEventListener('click', closeModal);
  }

  modal.addEventListener('click', (e) => {
    if (e.target === modal) {
      closeModal();
    }
  });

  window.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('active')) {
      closeModal();
    }
  });

  if (inquireBtn) {
    inquireBtn.addEventListener('click', () => {
      const activeTitle = titleEl ? titleEl.textContent : '';
      closeModal();
      const serviceSelect = document.getElementById('formService');
      const msgBox = document.getElementById('formMessage');
      if (serviceSelect && activeTitle) {
        if (activeTitle.includes('soustružení')) serviceSelect.value = 'kovoobrabeni';
        else if (activeTitle.includes('frézování')) serviceSelect.value = 'frezovani';
        else if (activeTitle.includes('přípravků')) serviceSelect.value = 'pripravky';
        else if (activeTitle.includes('GRIT') || activeTitle.includes('bruska')) serviceSelect.value = 'brusivo-stroje';
        else if (activeTitle.includes('EWM') || activeTitle.includes('TARA')) serviceSelect.value = 'svarovani';
        else if (activeTitle.includes('závitník') || activeTitle.includes('Vrtáky')) serviceSelect.value = 'nastroje';
        else if (activeTitle.includes('měřidla') || activeTitle.includes('SOMET')) serviceSelect.value = 'meridla';
      }
      if (msgBox && activeTitle) {
        msgBox.value = `Dobrý den,\nmáme zájem o poptávku technologie / výroby: ${activeTitle}.\nProsíme o kontaktování ohledně technických podrobností a termínu.`;
      }
    });
  }
}

function initScrollReveal() {
  const elements = document.querySelectorAll('.reveal-on-scroll');
  if (!('IntersectionObserver' in window)) {
    elements.forEach(el => el.classList.add('is-revealed'));
    return;
  }
  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-revealed');
        obs.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  elements.forEach(el => observer.observe(el));
}

function initCounters() {
  const counters = document.querySelectorAll('.counter');
  if (!('IntersectionObserver' in window)) {
    counters.forEach(c => c.textContent = c.getAttribute('data-target') || '0');
    return;
  }
  const obs = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        observer.unobserve(entry.target);
        if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
        const el = entry.target;
        el.textContent = '0';
        const target = parseInt(el.getAttribute('data-target') || '0', 10);
        let start = 0;
        const duration = 1200;
        const startTime = performance.now();
        function update(now) {
          const elapsed = now - startTime;
          const progress = Math.min(elapsed / duration, 1);
          const easeOut = 1 - Math.pow(1 - progress, 3);
          const current = Math.round(start + (target - start) * easeOut);
          el.textContent = String(current);
          if (progress < 1) {
            requestAnimationFrame(update);
          } else {
            el.textContent = String(target);
          }
        }
        requestAnimationFrame(update);
        observer.unobserve(el);
      }
    });
  }, { threshold: 0.5 });
  counters.forEach(c => obs.observe(c));
}

function initContactForm() {
  const form = document.getElementById('contactForm');
  const feedback = document.getElementById('formFeedback');
  const submitBtn = document.getElementById('formSubmitBtn');
  if (!form) return;
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    if (submitBtn) {
      submitBtn.disabled = true;
      submitBtn.textContent = 'Odesílám poptávku...';
    }
    setTimeout(() => {
      if (feedback) {
        feedback.style.display = 'block';
      }
      form.reset();
      if (submitBtn) {
        submitBtn.disabled = false;
        submitBtn.textContent = 'Odeslat nezávaznou poptávku';
      }
    }, 600);
  });
}

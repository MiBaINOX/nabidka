function openTechModal(id) {
  const item = catalogData[id];
  if (!item) return;

  const modal = document.getElementById("techModalBackdrop");
  if (!modal) return;

  document.getElementById("modalTitle").textContent = item.title;
  document.getElementById("modalSubtitle").textContent = item.subtitle;
  document.getElementById("modalImg").src = item.img;
  document.getElementById("modalImg").alt = item.title;
  document.getElementById("modalSysName").textContent = item.title;
  document.getElementById("modalUwBadge").textContent = item.uw;

  const featuresUl = document.getElementById("modalFeaturesList");
  featuresUl.innerHTML = "";
  item.features.forEach(function(feat) {
    const li = document.createElement("li");
    li.textContent = feat;
    featuresUl.appendChild(li);
  });

  const tableBody = document.querySelector("#modalSpecsTable tbody");
  tableBody.innerHTML = "";
  item.specs.forEach(function(row) {
    const tr = document.createElement("tr");
    const th = document.createElement("th");
    th.textContent = row[0];
    const td = document.createElement("td");
    td.textContent = row[1];
    tr.appendChild(th);
    tr.appendChild(td);
    tableBody.appendChild(tr);
  });

  const pdfLink = document.getElementById("modalPdfLink");
  if (pdfLink) {
    pdfLink.href = item.pdf;
  }

  modal.classList.add("active");
  document.body.style.overflow = "hidden";
}

function closeTechModal() {
  const modal = document.getElementById("techModalBackdrop");
  if (modal) {
    modal.classList.remove("active");
    document.body.style.overflow = "";
  }
}

document.addEventListener("DOMContentLoaded", function() {
  const modalClose = document.getElementById("techModalClose");
  if (modalClose) {
    modalClose.addEventListener("click", closeTechModal);
  }

  const modalBackdrop = document.getElementById("techModalBackdrop");
  if (modalBackdrop) {
    modalBackdrop.addEventListener("click", function(e) {
      if (e.target === modalBackdrop) {
        closeTechModal();
      }
    });
  }

  document.addEventListener("keydown", function(e) {
    if (e.key === "Escape") {
      closeTechModal();
    }
  });

  const filterButtons = document.querySelectorAll(".filter-tab-btn");
  const searchInput = document.getElementById("catalogSearch");
  const tierSelect = document.getElementById("insulationFilter");
  const cards = document.querySelectorAll(".cat-card");
  const countEl = document.getElementById("itemCount");

  function applyFilters() {
    let activeCat = "all";
    filterButtons.forEach(function(btn) {
      if (btn.classList.contains("active")) {
        activeCat = btn.getAttribute("data-filter");
      }
    });

    const query = searchInput ? searchInput.value.toLowerCase().trim() : "";
    const activeTier = tierSelect ? tierSelect.value : "all";

    let visibleCount = 0;

    cards.forEach(function(card) {
      const cardCat = card.getAttribute("data-cat");
      const cardTier = card.getAttribute("data-tier");
      const cardText = card.textContent.toLowerCase();

      const catMatches = (activeCat === "all" || cardCat === activeCat);
      const tierMatches = (activeTier === "all" || cardTier === activeTier);
      const queryMatches = (!query || cardText.indexOf(query) !== -1);

      if (catMatches && tierMatches && queryMatches) {
        card.style.display = "";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (countEl) {
      countEl.textContent = String(visibleCount);
    }
  }

  filterButtons.forEach(function(btn) {
    btn.addEventListener("click", function() {
      filterButtons.forEach(function(b) { b.classList.remove("active"); });
      btn.classList.add("active");
      applyFilters();
    });
  });

  if (searchInput) {
    searchInput.addEventListener("input", applyFilters);
  }

  if (tierSelect) {
    tierSelect.addEventListener("change", applyFilters);
  }

  const counterEls = document.querySelectorAll(".counter");
  if ("IntersectionObserver" in window) {
    const counterObserver = new IntersectionObserver(function(entries, observer) {
      entries.forEach(function(entry) {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const target = parseInt(el.getAttribute("data-target") || el.textContent, 10);
        if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
          observer.unobserve(el);
          return;
        }
        el.textContent = "0";
        const duration = 1400;
        const startTime = performance.now();

        function step(now) {
          const elapsed = now - startTime;
          const progress = Math.min(elapsed / duration, 1);
          const easeOut = 1 - Math.pow(1 - progress, 3);
          const current = Math.floor(easeOut * target);
          el.textContent = String(current);
          if (progress < 1) {
            requestAnimationFrame(step);
          } else {
            el.textContent = String(target);
          }
        }
        requestAnimationFrame(step);
        observer.unobserve(el);
      });
    }, { threshold: 0.2 });

    counterEls.forEach(function(c) {
      counterObserver.observe(c);
    });
  }

  const revealEls = document.querySelectorAll(".reveal-on-scroll");
  if ("IntersectionObserver" in window) {
    const revealObserver = new IntersectionObserver(function(entries, observer) {
      entries.forEach(function(entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add("revealed");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.1 });

    revealEls.forEach(function(r) {
      revealObserver.observe(r);
    });
  } else {
    revealEls.forEach(function(r) {
      r.classList.add("revealed");
    });
  }

  const menuToggle = document.getElementById("menuToggle");
  const mainNav = document.getElementById("mainNav");
  if (menuToggle && mainNav) {
    menuToggle.addEventListener("click", function() {
      mainNav.classList.toggle("active");
    });
    mainNav.querySelectorAll("a").forEach(function(link) {
      link.addEventListener("click", function() {
        mainNav.classList.remove("active");
      });
    });
  }

  const inquiryForm = document.getElementById("inquiryForm");
  const successMsg = document.getElementById("formSuccessMessage");
  if (inquiryForm && successMsg) {
    inquiryForm.addEventListener("submit", function(e) {
      e.preventDefault();
      successMsg.style.display = "block";
      inquiryForm.reset();
      setTimeout(function() {
        successMsg.scrollIntoView({ behavior: "smooth", block: "nearest" });
      }, 100);
    });
  }

  const urlParams = new URLSearchParams(window.location.search);
  if (urlParams.get("ref") === "nabidka") {
    const heroBadge = document.querySelector(".hero-badge.highlight");
    if (heroBadge) {
      heroBadge.textContent = "Připraveno pro STEMAK OKNA s.r.o. | Moderní B2B Prezentace";
    }
  }
});

let currentLang = "cs";

function setLanguage(lang) {
  if (!i18nData[lang]) return;
  currentLang = lang;
  localStorage.setItem("rostex_lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(function(el) {
    const key = el.getAttribute("data-i18n");
    if (i18nData[lang][key]) {
      el.textContent = i18nData[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-placeholder");
    if (i18nData[lang][key]) {
      el.setAttribute("placeholder", i18nData[lang][key]);
    }
  });

  document.querySelectorAll(".lang-btn").forEach(function(btn) {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });
}

function initCounters() {
  const counterEls = document.querySelectorAll(".counter");
  if (!counterEls.length) return;

  const observer = new IntersectionObserver(function(entries, obs) {
    entries.forEach(function(entry) {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const target = parseInt(el.getAttribute("data-target") || el.textContent, 10);
      obs.unobserve(el);

      if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
        el.textContent = target;
        return;
      }

      el.textContent = "0";
      const duration = 1600;
      const start = performance.now();

      function updateNumber(now) {
        const elapsed = now - start;
        const progress = Math.min(elapsed / duration, 1);
        const easeOut = 1 - Math.pow(1 - progress, 3);
        const current = Math.floor(easeOut * target);
        el.textContent = current;
        if (progress < 1) {
          requestAnimationFrame(updateNumber);
        } else {
          el.textContent = target;
        }
      }
      requestAnimationFrame(updateNumber);
    });
  }, { threshold: 0.2 });

  counterEls.forEach(function(el) {
    observer.observe(el);
  });
}

function initCatalogFilter() {
  const filterBtns = document.querySelectorAll(".filter-tab-btn");
  const pitchSelect = document.getElementById("pitchSelect");
  const searchInput = document.getElementById("searchInput");
  const cards = document.querySelectorAll(".cat-card");
  const counterEl = document.getElementById("searchCounter");

  let activeCategory = "all";
  let activePitch = "all";
  let searchQuery = "";

  function applyFilters() {
    let visibleCount = 0;
    cards.forEach(function(card) {
      const cardCategory = card.getAttribute("data-category") || "";
      const cardPitch = card.getAttribute("data-pitch") || "";
      const cardText = card.textContent.toLowerCase();

      const matchCategory = activeCategory === "all" || cardCategory === activeCategory;
      const matchPitch = activePitch === "all" || cardPitch.includes(activePitch);
      const matchSearch = !searchQuery || cardText.includes(searchQuery);

      if (matchCategory && matchPitch && matchSearch) {
        card.style.display = "";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (counterEl) {
      counterEl.textContent = visibleCount;
    }
  }

  filterBtns.forEach(function(btn) {
    btn.addEventListener("click", function() {
      filterBtns.forEach(function(b) { b.classList.remove("active"); });
      btn.classList.add("active");
      activeCategory = btn.getAttribute("data-category");
      applyFilters();
    });
  });

  if (pitchSelect) {
    pitchSelect.addEventListener("change", function() {
      activePitch = pitchSelect.value;
      applyFilters();
    });
  }

  if (searchInput) {
    searchInput.addEventListener("input", function() {
      searchQuery = searchInput.value.trim().toLowerCase();
      applyFilters();
    });
  }
}

function initTechModal() {
  const modalBackdrop = document.getElementById("techModalBackdrop");
  const modalClose = document.getElementById("techModalClose");
  const modalFooterClose = document.getElementById("modalFooterClose");
  if (!modalBackdrop) return;

  const titleEl = document.getElementById("modalTitle");
  const imgEl = document.getElementById("modalImg");
  const descEl = document.getElementById("modalDesc");
  const rcEl = document.getElementById("modalRc");
  const pitchEl = document.getElementById("modalPitch");
  const doorEl = document.getElementById("modalDoor");
  const finishEl = document.getElementById("modalFinish");
  const normEl = document.getElementById("modalNorm");
  const nbuEl = document.getElementById("modalNbu");
  const fireEl = document.getElementById("modalFire");

  function openModal(item) {
    if (!item) return;
    titleEl.textContent = item.name;
    imgEl.src = item.image;
    imgEl.alt = item.name;
    descEl.textContent = currentLang === "en" ? item.desc_en : item.desc_cs;
    rcEl.textContent = item.class_rc;
    pitchEl.textContent = item.pitch;
    doorEl.textContent = item.door_thickness;
    finishEl.textContent = item.finish;
    normEl.textContent = item.norm;
    nbuEl.textContent = item.nbu;
    fireEl.textContent = item.fire_rated;

    modalBackdrop.classList.add("active");
    modalBackdrop.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    modalBackdrop.classList.remove("active");
    modalBackdrop.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
  }

  document.querySelectorAll("[data-action='open-tech']").forEach(function(btn) {
    btn.addEventListener("click", function() {
      const itemId = btn.getAttribute("data-item-id");
      const found = catalogData.find(function(it) { return it.id === itemId; });
      if (found) {
        openModal(found);
      }
    });
  });

  if (modalClose) {
    modalClose.addEventListener("click", closeModal);
  }
  if (modalFooterClose) {
    modalFooterClose.addEventListener("click", closeModal);
  }

  modalBackdrop.addEventListener("click", function(e) {
    if (e.target === modalBackdrop) {
      closeModal();
    }
  });

  document.addEventListener("keydown", function(e) {
    if (e.key === "Escape" && modalBackdrop.classList.contains("active")) {
      closeModal();
    }
  });
}

function initNavigation() {
  const menuToggle = document.getElementById("menuToggle");
  const mainNav = document.getElementById("mainNav");
  if (menuToggle && mainNav) {
    menuToggle.addEventListener("click", function() {
      mainNav.classList.toggle("mobile-open");
    });

    mainNav.querySelectorAll("a").forEach(function(link) {
      link.addEventListener("click", function() {
        mainNav.classList.remove("mobile-open");
      });
    });
  }
}

function initContactForm() {
  const form = document.getElementById("inquiryForm");
  const alertEl = document.getElementById("formAlert");
  if (!form || !alertEl) return;

  form.addEventListener("submit", function(e) {
    e.preventDefault();
    alertEl.style.display = "block";
    alertEl.textContent = i18nData[currentLang].form_success;
    form.reset();
    setTimeout(function() {
      alertEl.style.display = "none";
    }, 6000);
  });
}

function checkRefNabidka() {
  const params = new URLSearchParams(window.location.search);
  if (params.get("ref") === "nabidka") {
    const banner = document.getElementById("nabidkaBanner");
    if (banner) {
      banner.style.display = "block";
    }
  }
}

document.addEventListener("DOMContentLoaded", function() {
  const savedLang = localStorage.getItem("rostex_lang") || "cs";
  setLanguage(savedLang);

  document.querySelectorAll(".lang-btn").forEach(function(btn) {
    btn.addEventListener("click", function() {
      const l = btn.getAttribute("data-lang");
      setLanguage(l);
    });
  });

  initCounters();
  initCatalogFilter();
  initTechModal();
  initNavigation();
  initContactForm();
  checkRefNabidka();
});

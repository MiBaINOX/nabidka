document.addEventListener("DOMContentLoaded", () => {
  const navToggle = document.getElementById("navToggle");
  const mainNav = document.getElementById("mainNav");
  if (navToggle && mainNav) {
    navToggle.addEventListener("click", () => {
      mainNav.classList.toggle("active");
    });
    mainNav.querySelectorAll("a").forEach(link => {
      link.addEventListener("click", () => {
        mainNav.classList.remove("active");
      });
    });
  }

  const tabBtns = document.querySelectorAll(".tab-btn");
  const searchInput = document.getElementById("catalogSearch");
  const clearSearchBtn = document.getElementById("clearSearch");
  const catalogCards = document.querySelectorAll(".catalog-card");
  const itemCountEl = document.getElementById("itemCount");
  const noResultsEl = document.getElementById("noResultsMessage");
  const resetFilterBtn = document.getElementById("resetFilterBtn");

  let currentCategory = "all";
  let currentSearch = "";

  function filterCatalog() {
    let visibleCount = 0;
    const query = currentSearch.toLowerCase().trim();

    catalogCards.forEach(card => {
      const cardCategory = card.getAttribute("data-category");
      const cardText = card.textContent.toLowerCase();
      const matchesCategory = (currentCategory === "all") || (cardCategory === currentCategory);
      const matchesSearch = !query || cardText.includes(query);

      if (matchesCategory && matchesSearch) {
        card.style.display = "";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (itemCountEl) {
      itemCountEl.textContent = String(visibleCount);
    }

    if (noResultsEl) {
      if (visibleCount === 0) {
        noResultsEl.classList.remove("hidden");
      } else {
        noResultsEl.classList.add("hidden");
      }
    }
  }

  tabBtns.forEach(btn => {
    btn.addEventListener("click", () => {
      tabBtns.forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      currentCategory = btn.getAttribute("data-filter") || "all";
      filterCatalog();
    });
  });

  if (searchInput) {
    searchInput.addEventListener("input", (e) => {
      currentSearch = e.target.value;
      filterCatalog();
    });
  }

  if (clearSearchBtn && searchInput) {
    clearSearchBtn.addEventListener("click", () => {
      searchInput.value = "";
      currentSearch = "";
      filterCatalog();
      searchInput.focus();
    });
  }

  if (resetFilterBtn) {
    resetFilterBtn.addEventListener("click", () => {
      currentCategory = "all";
      currentSearch = "";
      if (searchInput) searchInput.value = "";
      tabBtns.forEach(b => {
        if (b.getAttribute("data-filter") === "all") {
          b.classList.add("active");
        } else {
          b.classList.remove("active");
        }
      });
      filterCatalog();
    });
  }

  const modal = document.getElementById("techModalBackdrop");
  const modalCloseBtn = document.getElementById("modalCloseBtn");
  const modalCloseAction = document.getElementById("modalCloseAction");
  const modalCategory = document.getElementById("modalCategory");
  const modalTitle = document.getElementById("modalTitle");
  const modalDesc = document.getElementById("modalDesc");
  const modalTableBody = document.getElementById("modalTableBody");
  const modalDemandBtn = document.getElementById("modalDemandBtn");
  const formMaterialSelect = document.getElementById("formMaterial");

  let activeModalTarget = null;

  function openModal(targetId) {
    const data = techCatalogData[targetId];
    if (!data || !modal) return;

    activeModalTarget = targetId;
    if (modalCategory) modalCategory.textContent = data.kategorie;
    if (modalTitle) modalTitle.textContent = data.nazev;
    if (modalDesc) modalDesc.textContent = data.popis;

    if (modalTableBody) {
      modalTableBody.innerHTML = "";
      data.parametry.forEach(item => {
        const tr = document.createElement("tr");
        const tdName = document.createElement("td");
        tdName.textContent = item.p;
        const tdVal = document.createElement("td");
        tdVal.textContent = item.v;
        tr.appendChild(tdName);
        tr.appendChild(tdVal);
        modalTableBody.appendChild(tr);
      });
    }

    modal.classList.remove("hidden");
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    if (!modal) return;
    modal.classList.add("hidden");
    document.body.style.overflow = "";
    activeModalTarget = null;
  }

  document.querySelectorAll(".btn-modal-open").forEach(btn => {
    btn.addEventListener("click", (e) => {
      e.stopPropagation();
      const targetId = btn.getAttribute("data-modal-target");
      if (targetId) openModal(targetId);
    });
  });

  if (modalCloseBtn) modalCloseBtn.addEventListener("click", closeModal);
  if (modalCloseAction) modalCloseAction.addEventListener("click", closeModal);

  if (modal) {
    modal.addEventListener("click", (e) => {
      if (e.target === modal) closeModal();
    });
  }

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && modal && !modal.classList.contains("hidden")) {
      closeModal();
    }
  });

  if (modalDemandBtn && formMaterialSelect) {
    modalDemandBtn.addEventListener("click", () => {
      if (activeModalTarget) {
        if (activeModalTarget === "pe-hadice-polohadice") formMaterialSelect.value = "pe-hadice";
        else if (activeModalTarget === "pe-plocha-smrstovaci") formMaterialSelect.value = "pe-plocha";
        else if (activeModalTarget === "parotesna-folie") formMaterialSelect.value = "parotesna";
        else if (activeModalTarget === "bublinkova-folie") formMaterialSelect.value = "bublinkova";
        else if (activeModalTarget === "stretch-folie-strojni") formMaterialSelect.value = "stretch-strojni";
        else if (activeModalTarget === "stretch-folie-rucni") formMaterialSelect.value = "stretch-rucni";
        else if (activeModalTarget === "prumyslove-pytle-sacky") formMaterialSelect.value = "pytle-sacky";
        else if (activeModalTarget === "prekryvaci-plachty-pasky") formMaterialSelect.value = "plachty-pasky";
      }
      closeModal();
    });
  }

  const counters = document.querySelectorAll(".counter");
  if (counters.length > 0) {
    const counterObserver = new IntersectionObserver((entries, obs) => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const target = parseInt(el.getAttribute("data-target") || el.textContent, 10);
        if (isNaN(target)) {
          obs.unobserve(el);
          return;
        }

        if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
          el.textContent = String(target);
          obs.unobserve(el);
          return;
        }

        el.textContent = "0";
        const duration = 1400;
        const startTime = performance.now();

        function updateCounter(currentTime) {
          const elapsed = currentTime - startTime;
          const progress = Math.min(elapsed / duration, 1);
          const easeOut = 1 - Math.pow(1 - progress, 3);
          const currentVal = Math.floor(easeOut * target);
          el.textContent = String(currentVal);

          if (progress < 1) {
            requestAnimationFrame(updateCounter);
          } else {
            el.textContent = String(target);
          }
        }

        requestAnimationFrame(updateCounter);
        obs.unobserve(el);
      });
    }, { threshold: 0.25 });

    counters.forEach(c => counterObserver.observe(c));
  }

  const revealElements = document.querySelectorAll(".reveal");
  if (revealElements.length > 0) {
    const revealObserver = new IntersectionObserver((entries, obs) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add("revealed");
          obs.unobserve(entry.target);
        }
      });
    }, { threshold: 0.1 });

    revealElements.forEach(el => revealObserver.observe(el));
  }

  const urlParams = new URLSearchParams(window.location.search);
  const isProposal = urlParams.get("ref") === "nabidka";
  const proposalBanner = document.getElementById("proposalBanner");
  const closeBannerBtn = document.getElementById("closeBannerBtn");

  if (isProposal && proposalBanner) {
    proposalBanner.classList.remove("hidden");
  }

  if (closeBannerBtn && proposalBanner) {
    closeBannerBtn.addEventListener("click", () => {
      proposalBanner.classList.add("hidden");
    });
  }
});

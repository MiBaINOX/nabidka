function initCounters() {
  const counterEls = document.querySelectorAll('.counter[data-target]');
  if (!counterEls.length) return;

  const observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      observer.unobserve(el);

      const targetVal = parseInt(el.getAttribute('data-target') || el.textContent, 10);
      if (isNaN(targetVal)) return;

      if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        el.textContent = targetVal;
        return;
      }

      el.textContent = '0';
      const duration = 1600;
      const startTime = performance.now();

      function updateNumber(now) {
        const elapsed = now - startTime;
        const progress = Math.min(elapsed / duration, 1);
        const easeOut = 1 - Math.pow(1 - progress, 3);
        const current = Math.floor(easeOut * targetVal);
        el.textContent = current;

        if (progress < 1) {
          requestAnimationFrame(updateNumber);
        } else {
          el.textContent = targetVal;
        }
      }

      requestAnimationFrame(updateNumber);
    });
  }, { threshold: 0.25 });

  counterEls.forEach(function (el) {
    observer.observe(el);
  });
}

function initScrollReveal() {
  const revealElements = document.querySelectorAll('.reveal-on-scroll');
  if (!revealElements.length) return;

  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    revealElements.forEach(function (el) {
      el.classList.add('revealed');
    });
    return;
  }

  const observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        entry.target.classList.add('revealed');
        observer.unobserve(entry.target);
      }
    });
  }, {
    threshold: 0.12,
    rootMargin: '0px 0px -40px 0px'
  });

  revealElements.forEach(function (el) {
    observer.observe(el);
  });
}

function initCatalogFilters() {
  const filterBtns = document.querySelectorAll('.filter-tabs .tab-btn');
  const searchInput = document.getElementById('catalogSearch');
  const searchCounter = document.getElementById('searchCounter');
  const cards = document.querySelectorAll('#catalogGrid .cat-card');
  const itemCount = document.getElementById('itemCount');

  let activeFilter = 'all';
  let searchTerm = '';

  function applyFilter() {
    let visibleCount = 0;
    const term = searchTerm.trim().toLowerCase();

    cards.forEach(function (card) {
      const category = card.getAttribute('data-category');
      const text = card.textContent.toLowerCase();

      const matchesFilter = (activeFilter === 'all') || (category === activeFilter);
      const matchesSearch = (!term) || text.includes(term);

      if (matchesFilter && matchesSearch) {
        card.style.display = 'flex';
        visibleCount++;
      } else {
        card.style.display = 'none';
      }
    });

    if (searchCounter) {
      searchCounter.textContent = visibleCount + ' položek v katalogu';
    }
    if (itemCount && activeFilter === 'all' && !term) {
      itemCount.textContent = visibleCount;
    }
  }

  filterBtns.forEach(function (btn) {
    btn.addEventListener('click', function () {
      filterBtns.forEach(function (b) {
        b.classList.remove('active');
        b.setAttribute('aria-selected', 'false');
      });
      btn.classList.add('active');
      btn.setAttribute('aria-selected', 'true');
      activeFilter = btn.getAttribute('data-filter') || 'all';
      applyFilter();
    });
  });

  if (searchInput) {
    searchInput.addEventListener('input', function (e) {
      searchTerm = e.target.value;
      applyFilter();
    });
  }
}

function initTechModal() {
  const backdrop = document.getElementById('techModalBackdrop');
  const closeBtn = document.getElementById('techModalClose');
  const modalBody = document.getElementById('techModalBody');
  const modalTitle = document.getElementById('modalItemTitle');

  if (!backdrop || !modalBody) return;

  function openModal(itemId) {
    const item = TECH_CATALOG.find(function (it) {
      return it.id === itemId;
    });
    if (!item) return;

    if (modalTitle) {
      modalTitle.textContent = item.name;
    }

    let specsHtml = '';
    if (item.specs) {
      specsHtml += '<div class="table-responsive"><table class="modal-table"><tbody>';
      for (const key in item.specs) {
        if (Object.prototype.hasOwnProperty.call(item.specs, key)) {
          specsHtml += '<tr><th scope="row">' + key + '</th><td>' + item.specs[key] + '</td></tr>';
        }
      }
      specsHtml += '</tbody></table></div>';
    }

    modalBody.innerHTML =
      '<div class="modal-detail-grid">' +
        '<div class="modal-img-wrap">' +
          '<img src="' + item.image + '" alt="' + item.name + '" class="modal-img">' +
        '</div>' +
        '<div class="modal-desc-col">' +
          '<span class="modal-cat-tag">' + (item.categoryName || 'Výrobní program') + '</span>' +
          '<h4 class="modal-full-name">' + item.name + '</h4>' +
          '<p class="modal-full-text">' + item.full_desc + '</p>' +
        '</div>' +
      '</div>' +
      specsHtml +
      '<div class="modal-actions">' +
        '<a href="#kontakt" class="btn btn-primary" onclick="window.selectInquiryProduct(\'' + item.id + '\')">Poptat tento produkt</a>' +
      '</div>';

    backdrop.classList.add('open');
    backdrop.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';
  }

  function closeModal() {
    backdrop.classList.remove('open');
    backdrop.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
  }

  document.addEventListener('click', function (e) {
    const btn = e.target.closest('[data-open-id]');
    if (btn) {
      e.preventDefault();
      const id = btn.getAttribute('data-open-id');
      openModal(id);
    }
  });

  if (closeBtn) {
    closeBtn.addEventListener('click', closeModal);
  }

  backdrop.addEventListener('click', function (e) {
    if (e.target === backdrop) {
      closeModal();
    }
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && backdrop.classList.contains('open')) {
      closeModal();
    }
  });

  window.selectInquiryProduct = function (productId) {
    closeModal();
    const select = document.getElementById('formTyp');
    if (select) {
      for (let i = 0; i < select.options.length; i++) {
        if (productId.includes(select.options[i].value) || select.options[i].value.includes(productId)) {
          select.selectedIndex = i;
          break;
        }
      }
    }
  };
}

function initMobileMenu() {
  const toggleBtn = document.getElementById('mobileMenuBtn');
  const mainNav = document.querySelector('.main-nav');
  if (!toggleBtn || !mainNav) return;

  toggleBtn.addEventListener('click', function () {
    const isOpen = mainNav.classList.toggle('open');
    toggleBtn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
  });

  const navLinks = mainNav.querySelectorAll('.nav-link');
  navLinks.forEach(function (link) {
    link.addEventListener('click', function () {
      mainNav.classList.remove('open');
      toggleBtn.setAttribute('aria-expanded', 'false');
    });
  });
}

function initContactForm() {
  const form = document.getElementById('contactForm');
  const successMsg = document.getElementById('formSuccess');
  if (!form || !successMsg) return;

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    form.style.opacity = '0.5';
    setTimeout(function () {
      form.reset();
      form.style.opacity = '1';
      successMsg.style.display = 'block';
      setTimeout(function () {
        successMsg.style.display = 'none';
      }, 6000);
    }, 400);
  });
}

function initProposalMode() {
  const banner = document.getElementById('proposalBanner');
  if (!banner) return;
  const isProposal = window.location.search.includes('ref=nabidka') ||
                     window.location.pathname.includes('/nabidka/') ||
                     window.location.hash.includes('nabidka');
  if (isProposal) {
    banner.style.display = 'block';
  }
}

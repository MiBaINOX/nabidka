document.addEventListener('DOMContentLoaded', () => {
  const urlParams = new URLSearchParams(window.location.search);
  if (urlParams.get('ref') === 'nabidka') {
    const banner = document.getElementById('offerBanner');
    if (banner) {
      banner.style.display = 'block';
    }
  }

  const mobileToggle = document.getElementById('mobileToggle');
  const mainNav = document.getElementById('mainNav');
  if (mobileToggle && mainNav) {
    mobileToggle.addEventListener('click', () => {
      mainNav.classList.toggle('active');
    });
    mainNav.querySelectorAll('a').forEach(link => {
      link.addEventListener('click', () => {
        mainNav.classList.remove('active');
      });
    });
  }

  const revealElements = document.querySelectorAll('.reveal');
  if ('IntersectionObserver' in window) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.1 });
    revealElements.forEach(el => revealObserver.observe(el));
  } else {
    revealElements.forEach(el => el.classList.add('visible'));
  }

  const statNumbers = document.querySelectorAll('.stat-number');
  if ('IntersectionObserver' in window) {
    const statObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          const target = parseInt(entry.target.getAttribute('data-target'), 10);
          if (!isNaN(target)) {
            let current = 0;
            const duration = 1500;
            const stepTime = 30;
            const steps = duration / stepTime;
            const increment = target / steps;
            const timer = setInterval(() => {
              current += increment;
              if (current >= target) {
                entry.target.textContent = target;
                clearInterval(timer);
              } else {
                entry.target.textContent = Math.floor(current);
              }
            }, stepTime);
          }
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.2 });
    statNumbers.forEach(num => statObserver.observe(num));
  } else {
    statNumbers.forEach(num => {
      num.textContent = num.getAttribute('data-target');
    });
  }

  const catalogSearch = document.getElementById('catalogSearch');
  const filterBtns = document.querySelectorAll('#catalogFilters .filter-btn');
  const catalogCards = document.querySelectorAll('.catalog-item');
  const searchCounter = document.getElementById('searchCounter');

  let activeCategory = 'all';
  let searchQuery = '';

  function updateCatalog() {
    let visibleCount = 0;
    const query = searchQuery.trim().toLowerCase();

    catalogCards.forEach(card => {
      const cardCategory = card.getAttribute('data-category');
      const title = card.querySelector('.item-title').textContent.toLowerCase();
      const desc = card.querySelector('.item-desc').textContent.toLowerCase();

      const matchesCategory = (activeCategory === 'all' || cardCategory === activeCategory);
      const matchesSearch = (!query || title.includes(query) || desc.includes(query));

      if (matchesCategory && matchesSearch) {
        card.style.display = 'flex';
        visibleCount++;
      } else {
        card.style.display = 'none';
      }
    });

    if (searchCounter) {
      if (visibleCount === 1) {
        searchCounter.textContent = '1 technologie a systém v nabídce';
      } else if (visibleCount >= 2 && visibleCount <= 4) {
        searchCounter.textContent = visibleCount + ' technologie a systémy v nabídce';
      } else {
        searchCounter.textContent = visibleCount + ' technologií a systémů v nabídce';
      }
    }
  }

  filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      filterBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      activeCategory = btn.getAttribute('data-filter');
      updateCatalog();
    });
  });

  if (catalogSearch) {
    catalogSearch.addEventListener('input', (e) => {
      searchQuery = e.target.value;
      updateCatalog();
    });
  }

  const modalBackdrop = document.getElementById('techModalBackdrop');
  const modalClose = document.getElementById('techModalClose');
  const modalCatTag = document.getElementById('modalCatTag');
  const modalTitle = document.getElementById('modalTitle');
  const modalImg = document.getElementById('modalImg');
  const modalDesc = document.getElementById('modalDesc');
  const modalSpecsBody = document.getElementById('modalSpecsBody');
  const modalAdvantagesList = document.getElementById('modalAdvantagesList');
  const modalComponentsList = document.getElementById('modalComponentsList');

  function openTechModal(techId) {
    const item = TECH_CATALOG.find(t => t.id === techId);
    if (!item) return;

    if (modalCatTag) modalCatTag.textContent = item.category_name;
    if (modalTitle) modalTitle.textContent = item.title;
    if (modalImg) {
      modalImg.src = item.image;
      modalImg.alt = item.title;
    }
    if (modalDesc) modalDesc.textContent = item.description;

    if (modalSpecsBody) {
      modalSpecsBody.innerHTML = '';
      for (const [k, v] of Object.entries(item.specs)) {
        const row = document.createElement('tr');
        const tdK = document.createElement('td');
        tdK.textContent = k;
        const tdV = document.createElement('td');
        tdV.textContent = v;
        row.appendChild(tdK);
        row.appendChild(tdV);
        modalSpecsBody.appendChild(row);
      }
    }

    if (modalAdvantagesList) {
      modalAdvantagesList.innerHTML = '';
      item.advantages.forEach(adv => {
        const li = document.createElement('li');
        li.textContent = adv;
        modalAdvantagesList.appendChild(li);
      });
    }

    if (modalComponentsList) {
      modalComponentsList.innerHTML = '';
      item.components.forEach(cmp => {
        const li = document.createElement('li');
        li.textContent = cmp;
        modalComponentsList.appendChild(li);
      });
    }

    if (modalBackdrop) {
      modalBackdrop.classList.add('active');
      modalBackdrop.setAttribute('aria-hidden', 'false');
      document.body.style.overflow = 'hidden';
    }
  }

  function closeTechModal() {
    if (modalBackdrop) {
      modalBackdrop.classList.remove('active');
      modalBackdrop.setAttribute('aria-hidden', 'true');
      document.body.style.overflow = '';
    }
  }

  document.querySelectorAll('.catalog-item [data-id]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const techId = btn.getAttribute('data-id');
      openTechModal(techId);
    });
  });

  if (modalClose) {
    modalClose.addEventListener('click', closeTechModal);
  }

  if (modalBackdrop) {
    modalBackdrop.addEventListener('click', (e) => {
      if (e.target === modalBackdrop) {
        closeTechModal();
      }
    });
  }

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modalBackdrop && modalBackdrop.classList.contains('active')) {
      closeTechModal();
    }
  });

  const contactForm = document.getElementById('contactForm');
  const formFeedback = document.getElementById('formFeedback');
  if (contactForm) {
    contactForm.addEventListener('submit', (e) => {
      e.preventDefault();
      if (formFeedback) {
        formFeedback.style.display = 'block';
      }
      contactForm.reset();
      setTimeout(() => {
        if (formFeedback) {
          formFeedback.style.display = 'none';
        }
      }, 5000);
    });
  }
});

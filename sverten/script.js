  const modalClose = document.getElementById('techModalClose');
  const modalCloseSec = document.getElementById('modalCloseSecondary');
  const modalBadge = document.getElementById('modalBadge');
  const modalTitle = document.getElementById('modalTitle');
  const modalDesc = document.getElementById('modalDesc');
  const modalTable = document.getElementById('modalTable');
  const modalFeatures = document.getElementById('modalFeatures');
  const modalInquire = document.getElementById('modalInquireBtn');

  function openTechModal(id) {
    const data = TECH_CATALOG[id];
    if (!data || !modal) return;

    modalBadge.textContent = data.badge;
    modalTitle.textContent = data.name;
    modalDesc.textContent = data.desc;

    let tableHtml = '<tbody>';
    for (const [k, v] of Object.entries(data.specs)) {
      tableHtml += `<tr><th>${k}</th><td>${v}</td></tr>`;
    }
    tableHtml += '</tbody>';
    modalTable.innerHTML = tableHtml;

    let featsHtml = '';
    data.features.forEach(function (feat) {
      featsHtml += `<li>${feat}</li>`;
    });
    modalFeatures.innerHTML = featsHtml;

    if (modalInquire) {
      modalInquire.setAttribute('href', '#kontakt');
    }

    modal.classList.add('active');
    modal.style.display = 'flex';
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';
  }

  function closeTechModal() {
    if (!modal) return;
    modal.classList.remove('active');
    modal.style.display = 'none';
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
  }

  catalogItems.forEach(function (card) {
    card.addEventListener('click', function (e) {
      const id = this.getAttribute('data-id');
      if (id) {
        openTechModal(id);
      }
    });
  });


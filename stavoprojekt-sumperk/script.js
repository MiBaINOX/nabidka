  const bTypeSelect = document.getElementById("calcBuildingType");
  const chkStudie = document.getElementById("chkStudie");
  const chkDur = document.getElementById("chkDur");
  const chkDsp = document.getElementById("chkDsp");
  const chkDps = document.getElementById("chkDps");
  const chkAd = document.getElementById("chkAd");
  const resWeeks = document.getElementById("resWeeks");

  function updateCalculator() {
    let baseMin = 4;
    let baseMax = 6;
    const type = bTypeSelect ? bTypeSelect.value : "pozemni";

    if (type === "prumysl") {
      baseMin += 2;
      baseMax += 4;
    } else if (type === "vh") {
      baseMin += 3;
      baseMax += 5;
    } else if (type === "rekonstrukce") {
      baseMin += 1;
      baseMax += 3;
    }

    let extraMin = 0;
    let extraMax = 0;
    if (chkStudie && chkStudie.checked) { extraMin += 2; extraMax += 3; }
    if (chkDur && chkDur.checked) { extraMin += 3; extraMax += 5; }
    if (chkDsp && chkDsp.checked) { extraMin += 4; extraMax += 6; }
    if (chkDps && chkDps.checked) { extraMin += 4; extraMax += 6; }
    if (chkAd && chkAd.checked) { extraMin += 1; extraMax += 2; }

    const totalMin = baseMin + extraMin;
    const totalMax = baseMax + extraMax;
    if (resWeeks) {
      resWeeks.textContent = totalMin + "–" + totalMax;
    }
  }

  if (bTypeSelect) bTypeSelect.addEventListener("change", updateCalculator);
  [chkStudie, chkDur, chkDsp, chkDps, chkAd].forEach(chk => {
    if (chk) chk.addEventListener("change", updateCalculator);
  });
  updateCalculator();

  const modal = document.getElementById("techModalBackdrop");
  const modalContent = document.getElementById("modalDynamicContent");
  const modalClose = document.getElementById("modalCloseBtn");

  function openModal(id) {
    const item = TECH_CATALOG.find(x => x.id === id);
    if (!item) return;

    let tableHtml = "";
    if (item.table) {
      let ths = item.table.headers.map(h => "<th>" + h + "</th>").join("");
      let trs = item.table.rows.map(r => "<tr>" + r.map(c => "<td>" + c + "</td>").join("") + "</tr>").join("");
      tableHtml = "<div class='modal-table-wrap'><table class='modal-table'><thead><tr>" + ths + "</tr></thead><tbody>" + trs + "</tbody></table></div>";
    }

    let featsHtml = item.features.map(f => "<li>" + f + "</li>").join("");

    modalContent.innerHTML = 
      "<div class='modal-header-block'>" +
        "<span class='modal-tag'>Autorizovaný ateliér</span>" +
        "<h3 class='modal-title'>" + item.title + "</h3>" +
        "<p class='modal-perex'>" + item.perex + "</p>" +
      "</div>" +
      "<h4 class='modal-section-title'>Rozsah a legislativní autorizace</h4>" +
      tableHtml +
      "<h4 class='modal-section-title'>Klíčové výhody ateliéru</h4>" +
      "<ul class='modal-features-list'>" + featsHtml + "</ul>" +
      "<div class='modal-actions'>" +
        "<a href='#kontakt' class='btn-primary' onclick='closeModalFromBtn()'>Poptat tento projekt</a>" +
      "</div>";

    modal.style.display = "flex";
    modal.setAttribute("aria-hidden", "false");
  }


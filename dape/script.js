function initCalculator() {
  const selConstruction = document.getElementById("calcConstruction");
  const inpArea = document.getElementById("calcArea");
  const selSystem = document.getElementById("calcSystem");
  const resSavedThick = document.getElementById("resSavedThick");
  const resDeltaR = document.getElementById("resDeltaR");
  const resSd = document.getElementById("resSd");
  const resVolume = document.getElementById("resVolume");
  const resNote = document.getElementById("resNote");

  if (!selConstruction || !inpArea || !selSystem) return;

  function recalculate() {
    const area = parseFloat(inpArea.value) || 100;
    const sys = selSystem.value;

    let savedMm = 60;
    let deltaR = "+1,12 m²K/W";
    let sd = "1578 m";
    let note = "Nahrazuje 5 až 7 cm běžné minerální vaty, přerušuje krokve a odráží 95 % tepla.";

    if (sys === "aba") {
      savedMm = 60;
      deltaR = "+1,12 m²K/W";
      sd = "1578 m";
      note = "Nahrazuje 5 až 7 cm minerální vaty, přerušuje tepelné mosty a chrání proti letnímu přehřívání.";
    } else if (sys === "abmax") {
      savedMm = 75;
      deltaR = "+1,47 m²K/W";
      sd = "1578 m";
      note = "Zesílená vrstva 7 mm s vysokým tepelným odporem pro nízkoenergetické střešní pláště.";
    } else if (sys === "polareco") {
      savedMm = 160;
      deltaR = "+3,65 m²K/W";
      sd = "1730 m";
      note = "Sendvičová izolace POLAR ECO nahradí až 16 cm vaty při tloušťce pouhých 25 mm.";
    } else if (sys === "polarplus") {
      savedMm = 200;
      deltaR = "+4,15 m²K/W";
      sd = "1730 m";
      note = "Špičkový sendvič POLAR+ nahradí až 20 cm minerální vaty při zachování světlé výšky podkroví.";
    } else if (sys === "ap3") {
      savedMm = 40;
      deltaR = "+0,97 m²K/W";
      sd = "1378 m";
      note = "Odráží tepelné paprsky podlahového topení nahoru do potěru a tlumí kročejový hluk.";
    }

    const savedVolM3 = ((area * (savedMm / 1000))).toFixed(1);

    if (resSavedThick) resSavedThick.textContent = savedMm + " mm";
    if (resDeltaR) resDeltaR.textContent = deltaR;
    if (resSd) resSd.textContent = sd;
    if (resVolume) resVolume.textContent = savedVolM3.replace(".", ",") + " m³";
    if (resNote) resNote.textContent = note;
  }

  selConstruction.addEventListener("change", recalculate);
  inpArea.addEventListener("input", recalculate);
  selSystem.addEventListener("change", recalculate);
}

function initCatalogFilters() {
  const tabBtns = document.querySelectorAll(".filter-tabs .tab-btn");
  const searchInput = document.getElementById("catalogSearch");
  const cards = document.querySelectorAll(".catalog-grid .cat-card");
  const counter = document.getElementById("searchCounter");

  if (!cards.length) return;

  let activeFilter = "all";
  let searchQuery = "";

  function applyFilters() {
    let visibleCount = 0;

    cards.forEach(card => {
      const cardCat = card.getAttribute("data-category") || "";
      const cardText = card.textContent.toLowerCase();

      const matchesCat = (activeFilter === "all" || cardCat === activeFilter);
      const matchesSearch = (!searchQuery || cardText.includes(searchQuery));

      if (matchesCat && matchesSearch) {
        card.style.display = "flex";
        visibleCount++;
      } else {
        card.style.display = "none";
      }
    });

    if (counter) {
      if (activeFilter === "all" && !searchQuery) {
        counter.textContent = "Zobrazeno 14 termoizolačních systémů";
      } else {
        counter.textContent = "Zobrazeno " + visibleCount + " systémů z 14";
      }
    }
  }

  tabBtns.forEach(btn => {
    btn.addEventListener("click", function() {
      tabBtns.forEach(b => b.classList.remove("active"));
      this.classList.add("active");
      activeFilter = this.getAttribute("data-filter") || "all";
      applyFilters();
    });
  });

  if (searchInput) {
    searchInput.addEventListener("input", function() {
      searchQuery = this.value.trim().toLowerCase();
      applyFilters();
    });
  }
}

function initTechModal() {
  const backdrop = document.getElementById("techModalBackdrop");
  const closeBtn = document.getElementById("techModalClose");
  const closeSec = document.getElementById("modalCloseSecondary");
  const modalTitle = document.getElementById("modalTitle");
  const modalBadge = document.getElementById("modalBadge");
  const modalImg = document.getElementById("modalImg");
  const modalDesc = document.getElementById("modalDesc");
  const modalHighlights = document.getElementById("modalHighlights");
  const modalTableBody = document.getElementById("modalTableBody");
  const modalMontazList = document.getElementById("modalMontazList");

  if (!backdrop) return;

  function openModal(id) {
    const item = TECH_DATA[id];
    if (!item) return;

    if (modalTitle) modalTitle.textContent = item.name;
    if (modalBadge) modalBadge.textContent = item.badge;
    if (modalImg) {
      modalImg.src = item.image;
      modalImg.alt = item.name;
    }
    if (modalDesc) modalDesc.textContent = item.desc;

    if (modalHighlights) {
      modalHighlights.innerHTML = "";
      item.highlights.forEach(h => {
        const span = document.createElement("span");
        span.className = "tm-pill";
        span.textContent = h;
        modalHighlights.appendChild(span);
      });
    }

    if (modalTableBody) {
      modalTableBody.innerHTML = "";
      item.specs.forEach(pair => {
        const tr = document.createElement("tr");
        const td1 = document.createElement("td");
        td1.textContent = pair[0];
        const td2 = document.createElement("td");
        td2.textContent = pair[1];
        tr.appendChild(td1);
        tr.appendChild(td2);
        modalTableBody.appendChild(tr);
      });
    }

    if (modalMontazList) {
      modalMontazList.innerHTML = "";
      item.montaz.forEach(m => {
        const li = document.createElement("li");
        li.textContent = m;
        modalMontazList.appendChild(li);
      });
    }

    backdrop.classList.add("active");
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    backdrop.classList.remove("active");
    document.body.style.overflow = "";
  }

  document.querySelectorAll(".btn-tech-modal").forEach(btn => {
    btn.addEventListener("click", function() {
      const id = this.getAttribute("data-modal-id");
      openModal(id);
    });
  });

  if (closeBtn) closeBtn.addEventListener("click", closeModal);
  if (closeSec) closeSec.addEventListener("click", closeModal);

  backdrop.addEventListener("click", function(e) {
    if (e.target === backdrop) {
      closeModal();
    }
  });

  document.addEventListener("keydown", function(e) {
    if (e.key === "Escape" && backdrop.classList.contains("active")) {
      closeModal();
    }
  });
}

